"""Original NROM diagnostic. No external assembler or copyrighted ROM needed."""
from pathlib import Path

code = bytearray()
labels = {}
fixups = []

def emit(*values):
    code.extend(values)

def label(name):
    labels[name] = 0x8000 + len(code)

def branch(op, target):
    emit(op, 0)
    fixups.append((len(code)-1, target, True))

def addr(op, target):
    emit(op, 0, 0)
    fixups.append((len(code)-2, target, False))

label('reset')
emit(0x78, 0xD8, 0xA2, 0xFF, 0x9A, 0xE8)  # SEI CLD LDX #ff TXS INX
emit(0x8E, 0x00, 0x20, 0x8E, 0x01, 0x20)  # disable PPU
label('vblank1'); emit(0x2C, 0x02, 0x20); branch(0x10, 'vblank1')
label('vblank2'); emit(0x2C, 0x02, 0x20); branch(0x10, 'vblank2')
# Initialize RAM and hide all unused sprites.
emit(0xA9, 0, 0xA2, 0)
label('clear'); emit(0x95, 0, 0xE8); branch(0xD0, 'clear')
emit(0xA9, 0xFF)
label('hide'); emit(0x9D, 0x00, 0x02, 0xE8); branch(0xD0, 'hide')
for address,value in [(0x20,ord('R')),(0x21,ord('E')),(0x22,ord('A')),(0x23,ord('N'))]:
    emit(0xA9,value,0x85,address)
for address,value in [(0x0200,79),(0x0201,2),(0x0202,0),(0x0203,80)]:
    emit(0xA9,value,0x8D,address&255,address>>8)
# Initialize all nametables (vertical mirroring) with solid tile 1.
emit(0xA9,0x20,0x8D,0x06,0x20,0xA9,0,0x8D,0x06,0x20,0xA0,8,0xA2,0,0xA9,1)
label('fill'); emit(0x8D,0x07,0x20,0xE8); branch(0xD0,'fill'); emit(0x88); branch(0xD0,'fill')
# Clear attribute tables in both physical nametables.
for high in (0x23,0x27):
    emit(0xA9,high,0x8D,0x06,0x20,0xA9,0xC0,0x8D,0x06,0x20,0xA2,64,0xA9,0)
    name=f'attr{high}';label(name);emit(0x8D,0x07,0x20,0xCA);branch(0xD0,name)
emit(0xA9,0x3F,0x8D,0x06,0x20,0xA9,0,0x8D,0x06,0x20,0xA2,0)
label('palette');addr(0xBD,'colors');emit(0x8D,0x07,0x20,0xE8,0xE0,32);branch(0xD0,'palette')
emit(0xA9,2,0x8D,0x14,0x40,0xA9,0,0x8D,0x05,0x20,0x8D,0x05,0x20)
emit(0xA9,0x80,0x8D,0x00,0x20,0xA9,0x1E,0x8D,0x01,0x20)
label('main');addr(0x4C,'main')
label('nmi')
emit(0x48,0x8A,0x48,0x98,0x48)  # preserve A X Y
emit(0xE6,0,0xA9,1,0x8D,0x16,0x40,0xA9,0,0x8D,0x16,0x40,0x85,0x10,0xA2,8)
label('buttons');emit(0xAD,0x16,0x40,0x4A,0x66,0x10,0xCA);branch(0xD0,'buttons')
emit(0x68,0xA8,0x68,0xAA,0x68,0x40)
label('irq');emit(0x40)
label('colors');emit(*([0x0F,0x21,0x16,0x30]*4+[0x0F,0x16,0x2A,0x30]*4))
for offset,target,relative in fixups:
    value=labels[target]
    if relative:
        delta=value-(0x8000+offset+1)
        assert -128 <= delta <= 127
        code[offset]=delta&255
    else:
        code[offset:offset+2]=value.to_bytes(2,'little')
prg=bytearray([0xEA]*16384);prg[:len(code)]=code
for offset,name in [(0x3FFA,'nmi'),(0x3FFC,'reset'),(0x3FFE,'irq')]:
    prg[offset:offset+2]=labels[name].to_bytes(2,'little')
chr_data=bytearray(8192)
chr_data[16:24]=bytes([0xFF]*8)  # tile 1: pattern value 1
chr_data[32:40]=bytes([0xFF]*8)  # tile 2: pattern value 3
chr_data[40:48]=bytes([0xFF]*8)
output=Path(__file__).parent/'test-output'/'inspection-test.nes'
output.parent.mkdir(exist_ok=True)
output.write_bytes(b'NES\x1a'+bytes([1,1,1,0])+bytes(8)+prg+chr_data)
print(output)
